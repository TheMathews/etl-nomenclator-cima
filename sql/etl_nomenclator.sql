-- ==============================================================================
-- Script de Creación: Trazabilidad y Log de la ETL de CIMA (Nomenclátor)
-- Motor: Oracle Database
-- ==============================================================================

-- 1. DROP DE TABLAS (Borrado seguro por si existen)
BEGIN
   EXECUTE IMMEDIATE 'DROP TABLE etl_nomenclator_ficheros_procesados CASCADE CONSTRAINTS';
EXCEPTION WHEN OTHERS THEN IF SQLCODE != -942 THEN RAISE; END IF;
END;
/

BEGIN
   EXECUTE IMMEDIATE 'DROP TABLE etl_nomenclator CASCADE CONSTRAINTS';
EXCEPTION WHEN OTHERS THEN IF SQLCODE != -942 THEN RAISE; END IF;
END;
/

-- ==============================================================================
-- 2. TABLA MAESTRA: etl_nomenclator
-- Registra cada ejecución global del proceso de descarga (el ZIP completo).
-- ==============================================================================
CREATE TABLE etl_nomenclator (
    id_ejecucion NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha_inicio TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    fecha_fin TIMESTAMP,
    fichero_hash VARCHAR2(64) NOT NULL,
    estado VARCHAR2(20) NOT NULL,
    registros_insertados NUMBER DEFAULT 0,
    fecha_datos VARCHAR2(10),
    error_log CLOB
);

-- Índices tabla maestra
CREATE INDEX idx_etl_nomenclator_hash ON etl_nomenclator(fichero_hash);

-- Documentación tabla maestra
COMMENT ON TABLE etl_nomenclator IS 'Tabla maestra de auditoría. Registra cada descarga y ejecución global del archivo ZIP de CIMA.';
COMMENT ON COLUMN etl_nomenclator.id_ejecucion IS 'Identificador único y autoincremental de la ejecución de la ETL.';
COMMENT ON COLUMN etl_nomenclator.fecha_inicio IS 'Timestamp exacto en el que comenzó la descarga del ZIP.';
COMMENT ON COLUMN etl_nomenclator.fecha_fin IS 'Timestamp en el que finalizó el proceso global.';
COMMENT ON COLUMN etl_nomenclator.fichero_hash IS 'Hash SHA-256 del fichero ZIP descargado para control de duplicados a nivel global.';
COMMENT ON COLUMN etl_nomenclator.estado IS 'Estado de la ejecución: PROCESSING, SUCCESS, FAILED.';
COMMENT ON COLUMN etl_nomenclator.registros_insertados IS 'Total de registros insertados en todas las tablas temporales durante esta ejecución.';
COMMENT ON COLUMN etl_nomenclator.fecha_datos IS 'Fecha extraída del xml principal (listprescriptiondate) a nivel global.';
COMMENT ON COLUMN etl_nomenclator.error_log IS 'Trazabilidad de errores críticos si la descarga o validación del ZIP falla.';

-- ==============================================================================
-- 3. TABLA DE DETALLE: etl_nomenclator_ficheros_procesados
-- Registra el procesamiento individual de cada XML extraído del ZIP y sus métricas.
-- ==============================================================================
CREATE TABLE etl_nomenclator_ficheros_procesados (
    id_fichero NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_ejecucion NUMBER NOT NULL,
    nombre_fichero VARCHAR2(100) NOT NULL,
    marca_control VARCHAR2(100) NOT NULL,
    hash_logico VARCHAR2(64), -- <-- NUEVO CAMPO AÑADIDO AQUÍ
    tipo_control VARCHAR2(20) NOT NULL,
    estado VARCHAR2(20) NOT NULL,
    registros_procesados NUMBER DEFAULT 0,
    registros_nuevos NUMBER DEFAULT 0,
    registros_actualizados NUMBER DEFAULT 0,
    registros_borrados NUMBER DEFAULT 0,
    registros_reactivados NUMBER DEFAULT 0,
    fecha_proceso TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    error_log CLOB,
    CONSTRAINT fk_ficheros_ejecucion FOREIGN KEY (id_ejecucion) 
        REFERENCES etl_nomenclator(id_ejecucion) ON DELETE CASCADE
);

-- Índices tabla detalle
CREATE INDEX idx_etl_ficheros_marca ON etl_nomenclator_ficheros_procesados(nombre_fichero, marca_control);
CREATE INDEX idx_etl_ficheros_ejec_fk ON etl_nomenclator_ficheros_procesados(id_ejecucion);

-- Documentación tabla detalle
COMMENT ON TABLE etl_nomenclator_ficheros_procesados IS 'Tabla de detalle. Controla qué XMLs específicos se han procesado dentro de un ZIP y las métricas resultantes del cruce ELT.';
COMMENT ON COLUMN etl_nomenclator_ficheros_procesados.id_fichero IS 'Identificador único del registro de procesamiento del fichero.';
COMMENT ON COLUMN etl_nomenclator_ficheros_procesados.id_ejecucion IS 'Clave foránea que enlaza con la ejecución global en etl_nomenclator.';
COMMENT ON COLUMN etl_nomenclator_ficheros_procesados.nombre_fichero IS 'Nombre del archivo XML procesado (ej. DICCIONARIO_ATC.xml).';
COMMENT ON COLUMN etl_nomenclator_ficheros_procesados.marca_control IS 'Valor de control: el Hash SHA-256 (diccionarios) o la Fecha (Prescripcion.xml).';
COMMENT ON COLUMN etl_nomenclator_ficheros_procesados.hash_logico IS 'Hash SHA-256 calculado sobre el stream JSON de datos puros. Permite detectar cambios reales ignorando metadatos del XML.';
COMMENT ON COLUMN etl_nomenclator_ficheros_procesados.tipo_control IS 'Estrategia utilizada para la marca_control: HASH o FECHA.';
COMMENT ON COLUMN etl_nomenclator_ficheros_procesados.estado IS 'Estado del procesamiento de este fichero específico: SUCCESS, FAILED, SKIPPED.';
COMMENT ON COLUMN etl_nomenclator_ficheros_procesados.registros_procesados IS 'Total de registros extraídos del XML e insertados en la tabla temporal (Staging).';
COMMENT ON COLUMN etl_nomenclator_ficheros_procesados.registros_nuevos IS 'Número de registros nuevos insertados en la tabla maestra final.';
COMMENT ON COLUMN etl_nomenclator_ficheros_procesados.registros_actualizados IS 'Número de registros en los que se han detectado cambios (Hash distinto) y han sido actualizados.';
COMMENT ON COLUMN etl_nomenclator_ficheros_procesados.registros_borrados IS 'Número de registros dados de baja lógica (ya no vienen en el fichero XML actual).';
COMMENT ON COLUMN etl_nomenclator_ficheros_procesados.registros_reactivados IS 'Número de registros que estaban de baja y han vuelto a aparecer en el XML.';
COMMENT ON COLUMN etl_nomenclator_ficheros_procesados.fecha_proceso IS 'Timestamp de cuando se analizó/procesó este fichero.';
COMMENT ON COLUMN etl_nomenclator_ficheros_procesados.error_log IS 'Traza de error si la conversión XML o la carga en BD fallan.';